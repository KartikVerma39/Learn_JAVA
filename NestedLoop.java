public class NestedLoop {
    public static void main(String[] args){

//        nested loop = A loop inside other loop

        for(int i = 0 ; i <= 3 ; i++){
            for(int j = 0 ; j <= 6 ; j++){
                System.out.print(j + " ");
            }
            System.out.println();
        }
    }
}
